#!/usr/bin/env python3
"""
generate_color_tokens.py — emit the boilerplate's Swift color layer from the
canonical ODS YAML (vendored under Tools/tokens/).

  Tools/tokens/fluent2-primitives-1.0.yaml   (L1)  ─┐
  Tools/tokens/outlook-semantic-1.0.yaml      (L2)  ─┴─►  OutlookBackdrop/.../Tokens/Color/
                                                            ├── ColorPrimitives.swift
                                                            └── ColorSemantic.swift

ColorDynamic.swift (the Color(odsHex:) + odsDynamic helpers) is hand-written and
not generated. Re-vendor the YAML after a Figma re-export, then re-run this script.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
L1_YAML = ROOT / "Tools/tokens/fluent2-primitives-1.0.yaml"
L2_YAML = ROOT / "Tools/tokens/outlook-semantic-1.0.yaml"
OUT_DIR = ROOT / "OutlookBoilerplate/OutlookBackdrop/Sources/OutlookBackdrop/Tokens/Color"

MODES = ["light", "dark", "iosElevated", "lightHCC", "darkHCC"]
SKIP = ("androidSystem",)  # platform-native Android colors — not for an iOS boilerplate


# ---- minimal parsers for our own regular YAML (no pyyaml dependency) ----
def parse_primitives(text):
    out = {}
    for line in text.splitlines():
        m = re.match(r'^  ([\w.]+): "([^"]+)"', line)
        if m:
            out[m.group(1)] = m.group(2)
    return out


def parse_semantic(text):
    out, cur = {}, None
    for line in text.splitlines():
        mk = re.match(r"^  ([\w.]+):\s*$", line)
        if mk:
            cur = mk.group(1)
            out[cur] = {}
            continue
        mm = re.match(r"^    (\w+): \{ ref: (.+?), value: (.+?) \}", line)
        if mm and cur:
            mode, ref, val = mm.groups()
            ref = None if ref == "null" else ref.strip('"')
            val = None if val == "null" else val.strip('"')
            out[cur][mode] = {"ref": ref, "value": val}
    return out


# ---- name mapping ----
def prim_name(key):
    segs = key.split(".")
    return segs[0] + "".join(s[:1].upper() + s[1:] for s in segs[1:])


def sem_name(key):
    segs = key.split(".")
    if segs[-1] == "rest":
        segs = segs[:-1]
    return "ods" + "".join(s[:1].upper() + s[1:] for s in segs)


def cell_expr(cell):
    """Swift expression for one mode cell: primitive ref, semantic ref, or raw hex."""
    ref, val = cell["ref"], cell["value"]
    if ref is None:
        return f'Color(odsHex: "{val}")'
    if ref.startswith("semantic:"):
        return f"Color.{sem_name(ref.split('semantic:', 1)[1])}"
    return f"ODSPrimitive.{prim_name(ref)}"


def fallback(modes, m):
    if m in modes:
        return modes[m]
    if m == "iosElevated":
        return modes.get("dark") or modes["light"]
    if m == "lightHCC":
        return modes.get("light")
    if m == "darkHCC":
        return modes.get("dark") or modes["light"]
    return modes["light"]


def main():
    primitives = parse_primitives(L1_YAML.read_text())
    semantic = parse_semantic(L2_YAML.read_text())
    semantic = {k: v for k, v in semantic.items() if not any(s in k for s in SKIP)}

    # primitives to emit: every one referenced by L2 + the full commBlue & grey ramps
    referenced = set()
    for modes in semantic.values():
        for cell in modes.values():
            r = cell["ref"]
            if r and not r.startswith("semantic:"):
                referenced.add(r)
    emit = {k: v for k, v in primitives.items()
            if k in referenced or k.startswith("brand.commBlue.") or k.startswith("neutral.grey.")}
    missing = referenced - set(emit)
    if missing:
        print("ERROR: referenced primitives not in YAML:", sorted(missing)[:10])
        return 1

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    write_primitives(emit)
    write_semantic(semantic)

    minmodes = min(len(m) for m in semantic.values())
    print(f"primitives emitted: {len(emit)} / {len(primitives)}  (referenced: {len(referenced)})")
    print(f"semantic emitted:   {len(semantic)}  (modes/token min: {minmodes})")
    print(f"wrote {OUT_DIR.relative_to(ROOT)}/ColorPrimitives.swift")
    print(f"wrote {OUT_DIR.relative_to(ROOT)}/ColorSemantic.swift")
    return 0


HEADER = "// GENERATED by Tools/generate_color_tokens.py — DO NOT EDIT BY HAND.\n"


def write_primitives(emit):
    L = [HEADER,
         "// Layer 1 — Fluent 2 color primitives (the subset Outlook Mobile references,",
         "// plus the full Communication-blue and grey ramps for escape-hatch use).",
         '// Source: ods/ios/Foundations/Colors/fluent2-primitives-1.0.yaml',
         "",
         "import SwiftUI",
         "",
         "public enum ODSPrimitive {"]
    for k, v in emit.items():
        L.append(f'    public static let {prim_name(k)} = Color(odsHex: "{v}")')
    L.append("}")
    (OUT_DIR / "ColorPrimitives.swift").write_text("\n".join(L) + "\n")


def write_semantic(semantic):
    L = [HEADER,
         "// Layer 2 — Outlook Mobile semantic color tokens. Each resolves across the 5",
         "// Figma modes (light / dark / iOS-elevated / light-HC / dark-HC) via iOS traits,",
         "// referencing Layer 1 primitives — see odsDynamic in ColorDynamic.swift.",
         '// Source: ods/ios/Foundations/Colors/outlook-semantic-1.0.yaml',
         "",
         "import SwiftUI",
         "",
         "public extension Color {"]
    for key, modes in semantic.items():
        args = ", ".join(f"{m}: {cell_expr(fallback(modes, m))}" for m in MODES)
        L.append(f"    static var {sem_name(key)}: Color {{ odsDynamic({args}) }}")
    L.append("}")
    (OUT_DIR / "ColorSemantic.swift").write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    sys.exit(main())
